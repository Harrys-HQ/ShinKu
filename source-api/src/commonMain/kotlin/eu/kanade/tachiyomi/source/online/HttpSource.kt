    private val hasGetMangaUpdate by lazy {
        try {
            val sourceClass = Class.forName("eu.kanade.tachiyomi.source.Source")
            val httpSourceClass = Class.forName("eu.kanade.tachiyomi.source.online.HttpSource")
            this.javaClass.methods.any { method ->
                method.name == "getMangaUpdate" && 
                method.parameterTypes.size == 5 && 
                method.declaringClass != httpSourceClass && 
                method.declaringClass != sourceClass
            }
        } catch (e: Throwable) {
            false
        }
    }

    /**
     * Generates a unique ID for the source based on the provided [name], [lang] and
     * [versionId]. It will use the first 16 characters (64 bits) of the MD5 of the string
     * `"${name.lowercase()}/$lang/$versionId"`.
     *
     * Note: the generated ID sets the sign bit to `0`.
     *
     * Can be used to generate outdated IDs, such as when the source name or language
     * needs to be changed but migrations can be avoided.
     *
     * @since extensions-lib 1.5
     * @param name [String] the name of the source
     * @param lang [String] the language of the source
     * @param versionId [Int] the version ID of the source
     * @return a unique ID for the source
     */
    @Suppress("MemberVisibilityCanBePrivate")
    protected fun generateId(name: String, lang: String, versionId: Int): Long {
        val key = "${name.lowercase()}/$lang/$versionId"
        val bytes = MessageDigest.getInstance("MD5").digest(key.toByteArray())
        return (0..7).map { bytes[it].toLong() and 0xff shl 8 * (7 - it) }.reduce(Long::or) and Long.MAX_VALUE
    }

    /**
     * Headers builder for requests. Implementations can override this method for custom headers.
     */
    protected open fun headersBuilder() = Headers.Builder().apply {
        add("User-Agent", network.defaultUserAgentProvider())
    }

    /**
     * Visible name of the source.
     */
    override fun toString() = "$name (${lang.uppercase()})"

    /**
     * Get a page with a list of manga.
     * Normally it's not needed to override this method.
     *
     * @param page the page number to retrieve.
     */
    override suspend fun getPopularManga(page: Int): MangasPage {
        val result = fetchPopularManga(page).awaitSingle()
        result.mangas.forEach { manga ->
            manga.memo?.let { MangaMemoCache.put(id, manga.url, it) }
        }
        return result
    }

    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getPopularManga"))
    override fun fetchPopularManga(page: Int): Observable<MangasPage> {
        return client.newCall(popularMangaRequest(page))
            .asObservableSuccess()
            .map { response ->
                popularMangaParse(response)
            }
    }

    /**
