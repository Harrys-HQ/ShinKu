    override suspend fun getSearchManga(
        page: Int,
        query: String,
        filters: FilterList,
    ): MangasPage {
        val result = fetchSearchManga(page, query, filters).awaitSingle()
        result.mangas.forEach { manga ->
            manga.memo?.let { MangaMemoCache.put(id, manga.url, it) }
